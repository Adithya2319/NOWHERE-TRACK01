import { test, expect } from '@playwright/test';
const origin='http://127.0.0.1:4174';
async function login(page,name) {
  await page.goto('/login');
  await expect(page.getByText('Local accounts.', {exact:true})).toBeVisible();
  await page.getByRole('button',{name:`Enter as ${name}`,exact:true}).click();
  await expect(page.getByRole('heading',{name:'Your day plan'})).toBeVisible();
  await expect(page.getByText('Local workspace', {exact:true})).toBeVisible();
}
