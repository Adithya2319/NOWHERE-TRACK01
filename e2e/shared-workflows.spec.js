test('planner saves privately, membership is enforced and directory survives map failure',async({browser})=>{
  const context=await browser.newContext({viewport:{width:360,height:780}});
  const page=await context.newPage();const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.route('https://*.tile.openstreetmap.org/**',route=>route.abort());
  await login(page,'New Student');
  await page.goto('/rides');
  await expect(page.getByText(/Approved campus membership is needed/)).toBeVisible();
  await expect(page.getByRole('button',{name:'Review and request'}).first()).toBeDisabled();
  await page.goto('/marks');
  await page.getByLabel('Assessment rule mode').selectOption('demo');
  await page.getByLabel('Edit recorded values').check();
  const mark=page.getByLabel('26ETBS11 recorded Mid-term');
  await mark.fill('15');
  await page.getByRole('button',{name:'Save recorded marks & target'}).click();
  await expect(page.getByRole('status').filter({hasText:'Recorded marks, target and policy saved'})).toBeVisible();
  await page.reload();
  await expect(mark).toHaveValue('15');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:'tmp/browser-mobile-planner.png',fullPage:true});
  await page.goto('/directory');
  await page.getByLabel('Search directory').fill('robotics');
  await expect(page.getByRole('button',{name:'Demo robotics senior'})).toBeVisible();
  await expect(page.getByText(/Map tiles are unavailable/)).toBeVisible();
  await page.getByLabel('Search directory').fill('no-such-person');
  await expect(page.getByText('No directory entries match these filters.')).toBeVisible();
  await page.goto('/attendance');
  await page.route('**/api/attendance',route=>route.abort());
  await page.getByRole('button',{name:'Present: Mathematics-1 theory',exact:true}).click();
  await expect(page.getByRole('alert')).toBeVisible();
  expect((await (await page.request.get('/api/state')).json()).academics.semesters[1].events).toHaveLength(0);
  expect(errors).toEqual([]);
  await context.close();
});
